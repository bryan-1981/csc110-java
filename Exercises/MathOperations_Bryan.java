package Exercises;

public class MathOperations_Bryan {

	public static void main(String[] args) {
		
	double a =10.2;
	double b =7.6;
	double sum = a +b; 
	double difference = a - b;
	double product = a * b;
	
	System.out.println(a + " + " + b + " = " + sum);
	System.out.println(a + " - " + b + " = " + difference);
	System.out.println(a + " * " + b + " = " + product);
	      }

}
 	