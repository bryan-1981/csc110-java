package Exercises;

public class Unit1_EscapeSequences {

	public static void main(String[] args) {
		// Using \n means it writes what comes after it to a new line 
		System.out.println("Hello, \nWorld!");
		//using \t acts as a tab so like just a bigger space, helps efficency
		System.out.println("Hello, \tWorld!");
		// using\\ is placing a backsplash with the command \\
		System.out.println("This is a backslash: \\");
		// using the foward slash allows the dev to add quotations "" with these. without throwing off the string
		System.out.println("She said, \"Hello, World!\"");
	}

}
